"""Turn the Project Gutenberg plain-text Moby-Dick (ebook #2701) into book.js.

Usage:
    curl -L https://www.gutenberg.org/cache/epub/2701/pg2701.txt -o pg2701.txt
    python3 tools/build_book.py pg2701.txt > book.js
"""
import json
import re
import sys


def paragraphs(lines):
    text = "\n".join(lines)
    out = []
    for block in re.split(r"\n\s*\n", text):
        block = block.replace("_", "")  # italics markers
        block = re.sub(r"[‎‏]", "", block)
        block = re.sub(r"\s+", " ", block).strip()
        if block:
            out.append(block)
    return out


def main(path):
    raw = open(path, encoding="utf-8-sig").read().replace("\r\n", "\n")
    start = raw.index("*** START OF THE PROJECT GUTENBERG EBOOK")
    end = raw.index("*** END OF THE PROJECT GUTENBERG EBOOK")
    lines = raw[start:end].split("\n")

    # The table of contents repeats every heading, so only start scanning
    # at the last ETYMOLOGY heading, which is the real section.
    first = max(i for i, l in enumerate(lines) if l.strip() == "ETYMOLOGY.")
    heads = []  # (line index, title)
    for i in range(first, len(lines)):
        s = lines[i].strip()
        if s == "ETYMOLOGY.":
            heads.append((i, "Etymology"))
        elif s.startswith("EXTRACTS. (Supplied"):
            heads.append((i, "Extracts"))
        elif re.match(r"^CHAPTER \d+\. ", lines[i]):
            heads.append((i, s))
        elif s == "Epilogue" and lines[i] == "Epilogue":
            heads.append((i, "Epilogue"))

    chapters = []
    for n, (i, title) in enumerate(heads):
        stop = heads[n + 1][0] if n + 1 < len(heads) else len(lines)
        paras = paragraphs(lines[i + 1:stop])
        m = re.match(r"CHAPTER (\d+)\. (.*)", title)
        if m:
            label, name = f"Chapter {m.group(1)}", m.group(2).rstrip(".")
        else:
            label, name = title, ""
        chapters.append({"label": label, "title": name, "text": "\n".join(paras)})

    assert len(chapters) == 138, len(chapters)  # etymology, extracts, 135, epilogue
    sys.stdout.write("// Generated by tools/build_book.py from Project Gutenberg ebook #2701.\n")
    sys.stdout.write("window.BOOK = ")
    json.dump(chapters, sys.stdout, ensure_ascii=False, indent=0)
    sys.stdout.write(";\n")


if __name__ == "__main__":
    main(sys.argv[1])
